import { test } from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import { app } from '../src/app';
import { db } from '../src/db/database';

test('password, approval, session restoration and logout are enforced end to end', async () => {
  const email = `entry-${Date.now()}@example.test`;
  const password = 'synthetic-password-42';
  const signup = await request(app).post('/api/auth/signup').send({ email, password, name: 'Entry Regression', role: 'admin' });
  assert.equal(signup.status, 201);
  const id = signup.body.user.id;
  assert.equal(signup.body.user.status, 'pending');
  assert.equal(signup.body.user.role, 'operator');
  assert.ok(!JSON.stringify(signup.body).includes(password));
  assert.equal((await request(app).post('/api/auth/login').send({ email, password })).status, 403);
  assert.equal((await request(app).post('/api/auth/login').send({ email, password: 'wrong-password' })).status, 401);
  assert.equal((await request(app).patch(`/api/auth/users/${id}/approve`).send({ status: 'approved' })).status, 401);
  assert.equal((await request(app).patch(`/api/auth/users/${id}/approve`).set('Authorization', 'Bearer dev-viewer-token').send({ status: 'approved' })).status, 403);
  const approval = await request(app).patch(`/api/auth/users/${id}/approve`).set('Authorization', 'Bearer dev-admin-token').send({ status: 'approved', approvedBy: 'forged-identity' });
  assert.equal(approval.status, 200);
  assert.equal(approval.body.user.approvedBy, 'usr-admin-01');
  assert.equal((await request(app).post('/api/auth/login').send({ email })).status, 400);
  assert.equal((await request(app).post('/api/auth/login').send({ email, password: 'wrong-password' })).status, 401);
  const login = await request(app).post('/api/auth/login').send({ email, password });
  assert.equal(login.status, 200);
  const token = login.body.token;
  assert.ok(!token.includes(id), 'Session must not be derivable from public user ID');
  const me = await request(app).get('/api/auth/me').set('Authorization', `Bearer ${token}`);
  assert.equal(me.status, 200);
  assert.equal(me.body.user.id, id);
  assert.equal((await request(app).get('/api/auth/me')).status, 401);
  assert.equal((await request(app).get('/api/auth/me').set('Authorization', `Bearer sentinel-token-${id}`)).status, 401);
  assert.equal((await request(app).post('/api/vitalwatch/vitals').set('Authorization', `Bearer ${token}`).send({ recorderRole: 'admin' })).status, 403);
  assert.equal((await request(app).post('/api/auth/logout').set('Authorization', `Bearer ${token}`)).status, 200);
  assert.equal((await request(app).get('/api/auth/me').set('Authorization', `Bearer ${token}`)).status, 401);
  const second = await request(app).post('/api/auth/login').send({ email, password });
  assert.notEqual(second.body.token, token);
  db.resetToBaseline();
  assert.equal((await request(app).get('/api/auth/me').set('Authorization', `Bearer ${second.body.token}`)).status, 200, 'Scenario reset preserves accounts');
  db.approveUser(id, 'usr-admin-01', 'rejected');
  assert.equal((await request(app).get('/api/auth/me').set('Authorization', `Bearer ${second.body.token}`)).status, 401);
});
